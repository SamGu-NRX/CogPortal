/**
 * Syncs emoji/dist/ assets to the Discord application's emoji set and
 * regenerates src/emoji-manifest.generated.ts.
 *
 * Idempotent by name + content hash: unchanged assets are skipped. A changed
 * asset means delete + recreate (Discord has no image-update endpoint), which
 * assigns a NEW id; any message already rendered with the old id will show
 * raw `:name:` text. The script warns loudly when that happens. Keep names
 * stable; redesign images rarely and deliberately.
 *
 * Usage:
 *   DISCORD_BOT_TOKEN=... pnpm --filter @cogworks/discord-kit emoji:sync
 *   DISCORD_APPLICATION_ID overrides the course app id when trialing elsewhere.
 */
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const KIT_ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIST = path.join(KIT_ROOT, "emoji", "dist");
const MANIFEST_JSON = path.join(KIT_ROOT, "emoji", "manifest.json");
const MANIFEST_TS = path.join(KIT_ROOT, "src", "emoji-manifest.generated.ts");
const API = "https://discord.com/api/v10";

const token = process.env.DISCORD_BOT_TOKEN;
const applicationId = process.env.DISCORD_APPLICATION_ID ?? "1526706029356646460";
if (!token) {
  console.error("DISCORD_BOT_TOKEN is required. Nothing was changed.");
  process.exit(1);
}

async function discord(method, route, body) {
  for (let attempt = 0; attempt < 4; attempt += 1) {
    const response = await fetch(`${API}${route}`, {
      method,
      headers: {
        Authorization: `Bot ${token}`,
        "Content-Type": "application/json",
        "User-Agent": "DiscordBot (https://cogportal-dev.sillion.app, 1)",
      },
      body: body ? JSON.stringify(body) : undefined,
    });
    if (response.status === 429) {
      const payload = await response.json().catch(() => ({}));
      const waitMs = Math.ceil((payload.retry_after ?? 1) * 1_000);
      console.log(`  rate limited; waiting ${waitMs}ms`);
      await new Promise((resolve) => setTimeout(resolve, waitMs));
      continue;
    }
    if (!response.ok) {
      const detail = await response.text().catch(() => "");
      throw new Error(`${method} ${route} failed with HTTP ${response.status}: ${detail.slice(0, 300)}`);
    }
    return response.status === 204 ? null : response.json();
  }
  throw new Error(`${method} ${route} stayed rate limited.`);
}

const files = (await readdir(DIST)).filter((file) => /^cog_[a-z0-9_]+\.(png|gif)$/.test(file)).sort();
if (files.length === 0) {
  console.error("emoji/dist is empty; run `pnpm --filter @cogworks/discord-kit emoji:render` first.");
  process.exit(1);
}

const manifest = JSON.parse(await readFile(MANIFEST_JSON, "utf8").catch(() => "{}"));
const appManifest = manifest[applicationId] ?? {};
const existing = new Map(
  ((await discord("GET", `/applications/${applicationId}/emojis`)).items ?? []).map((emoji) => [emoji.name, emoji]),
);

const next = {};
let created = 0;
let recreated = 0;
let unchanged = 0;
for (const file of files) {
  const name = file.replace(/\.(png|gif)$/, "");
  const bytes = await readFile(path.join(DIST, file));
  const sourceHash = createHash("sha256").update(bytes).digest("hex").slice(0, 16);
  const mime = file.endsWith(".gif") ? "image/gif" : "image/png";
  const current = existing.get(name);

  if (current && appManifest[name]?.sourceHash === sourceHash && appManifest[name]?.id === current.id) {
    next[name] = { id: current.id, animated: Boolean(current.animated), sourceHash };
    unchanged += 1;
    continue;
  }
  if (current) {
    console.warn(`! ${name} changed: deleting and recreating. The new id orphans any message that already used the old one.`);
    await discord("DELETE", `/applications/${applicationId}/emojis/${current.id}`);
    recreated += 1;
  } else {
    created += 1;
  }
  const uploaded = await discord("POST", `/applications/${applicationId}/emojis`, {
    name,
    image: `data:${mime};base64,${bytes.toString("base64")}`,
  });
  next[name] = { id: uploaded.id, animated: Boolean(uploaded.animated), sourceHash };
  console.log(`+ ${name} -> ${uploaded.id}${uploaded.animated ? " (animated)" : ""}`);
}

manifest[applicationId] = next;
await writeFile(MANIFEST_JSON, `${JSON.stringify(manifest, null, 2)}\n`);

const header =
  "/**\n" +
  " * Generated by `pnpm --filter @cogworks/discord-kit emoji:sync`.\n" +
  " * Do not edit by hand; run the sync script against the Discord application\n" +
  " * and commit the result. Keyed by Discord application id.\n" +
  " */\n";
await writeFile(
  MANIFEST_TS,
  `${header}import type { EmojiManifest } from "./emoji.ts";\n\nexport const EMOJI_MANIFEST: EmojiManifest = ${JSON.stringify(manifest, null, 2)};\n`,
);

console.log(
  `Synced ${files.length} emoji for application ${applicationId}: ${created} created, ${recreated} recreated, ${unchanged} unchanged.`,
);
console.log(`Manifest written to ${path.relative(process.cwd(), MANIFEST_TS)}; commit it.`);
