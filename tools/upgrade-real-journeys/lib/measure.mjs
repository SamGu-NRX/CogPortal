// Measurement instrumentation. Builds alpha's Worker unchanged except for a
// shim entry: the shim imports the real worker/index.ts and wraps its fetch so
// every request's D1 binding calls (prepare/batch/exec statements) are counted
// and reported on a response header. No repo worker file is edited; the
// instrumented build is labeled as such in every receipt.
// Wall time is deliberately NOT reported: performance.now around a fetch is
// not Worker CPU. Receipts report the 10 ms Worker CPU budget as UNMEASURED
// until real workerd CPU telemetry (wrangler dev tail / inspector) is wired
// in; D1 statement counts per request remain the measured signal.
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SUITE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export function writeShim(checkoutDir) {
  const portal = path.join(checkoutDir, "apps", "portal");
  const shimDir = path.join(SUITE, ".generated");
  mkdirSync(shimDir, { recursive: true });
  const shim = path.join(shimDir, `worker-shim.${path.basename(checkoutDir)}.ts`);
  const rel = path.relative(shimDir, path.join(portal, "worker", "index.ts"));
  writeFileSync(
    shim,
    `// Generated by tools/upgrade-real-journeys/lib/measure.mjs - measurement shim.
// Imports the REAL worker entry and wraps fetch to count D1 binding calls per
// request. Nothing else changes: same routes, same services, same D1 file.
import realWorker from "${rel}";
import { countD1Proxy } from "./d1-proxy";
import { echoResponse } from "./response-echo";

type Env = { DB: unknown } & Record<string, unknown>;

export default {
  async fetch(request: Request, rawEnv: Env, ctx: ExecutionContext): Promise<Response> {
    const state = { statements: 0 };
    const env: Env = { ...rawEnv, DB: countD1Proxy(rawEnv.DB, state) };
    try {
      const res = await realWorker.fetch(request, env as never, ctx);
      return echoResponse(res, state.statements);
    } catch (e) {
      console.error("[upgrade-suite] request failed:", (e as Error).message);
      throw e;
    }
  },
};
`,
  );
  writeFileSync(
    path.join(shimDir, "d1-proxy.ts"),
    `// Counts D1 statements issued through the binding during one request.
function statementCount(sql: string): number {
  let count = 0;
  for (const part of sql.split(";")) {
    if (part.trim().length > 0) count += 1;
  }
  return count;
}
export function countD1Proxy(db: D1Database, state: { statements: number }): D1Database {
  const wrap = <T extends object>(obj: T): T =>
    new Proxy(obj, {
      get(target, prop) {
        const v = Reflect.get(target, prop);
        if (typeof v !== "function") return v;
        return (...args: unknown[]) => {
          if (prop === "batch" && Array.isArray(args[0])) {
            // Each statement handed to batch executes exactly once.
            state.statements += args[0].length;
          } else if (prop === "exec") {
            // exec runs every ;-separated statement in its SQL.
            state.statements += statementCount(String(args[0] ?? ""));
          } else if (
            prop === "all" || prop === "run" || prop === "first" || prop === "raw" || prop === "get"
          ) {
            // Execution happens on the prepared (or bound) statement.
            state.statements += 1;
          }
          const r = (v as (...a: unknown[]) => unknown).apply(target, args);
          return r && typeof r === "object" && !(r instanceof Promise) ? wrap(r as object) : r;
        };
      },
    });
  return wrap(db);
}
`,
  );
  writeFileSync(
    path.join(shimDir, "response-echo.ts"),
    `// Replays a Worker response with the measurement header attached, without
// breaking the responses the standard Response constructor cannot represent.
// WebSocket upgrades (Cloudflare pairs the client socket in \`webSocket\`,
// status 101) must pass through untouched: a 101 is not a constructible
// status, and rebuilding the response would drop the paired socket.
export function echoResponse(res: Response, queries: number): Response {
  const upgraded = res as Response & { webSocket?: unknown };
  if (res.status === 101 || upgraded.webSocket) {
    return res;
  }
  const headers = new Headers(res.headers);
  headers.set("x-upgrade-suite-queries", String(queries));
  return new Response(res.body, { status: res.status, statusText: res.statusText, headers });
}
`,
  );
  return shim;
}

/** Instrumented vite config: app plugins with the shim as the worker main. */
export function writeInstrumentedViteConfig(checkoutDir, shimPath) {
  const portal = path.join(checkoutDir, "apps", "portal");
  // The config must be generated INSIDE the target portal package: under the
  // pnpm layout the plugins it imports (@vitejs/plugin-react,
  // @tailwindcss/vite, @cloudflare/vite-plugin) are declared only by
  // apps/portal, so a config generated under the suite's own .generated
  // directory cannot resolve them. From inside the package, Node resolves the
  // imports through the portal's own node_modules.
  const cfgDir = path.join(portal, ".upgrade-suite");
  mkdirSync(cfgDir, { recursive: true });
  const cfg = path.join(cfgDir, `vite.config.measured.mjs`);
  const rel = path.relative(cfgDir, portal).replaceAll("\\\\", "/");
  writeFileSync(
    cfg,
    `import { defineConfig, mergeConfig } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
import { cloudflare } from "@cloudflare/vite-plugin";

const shim = ${JSON.stringify(shimPath)};

export default mergeConfig(
  defineConfig({
    plugins: [react(), tailwindcss(), cloudflare({ main: shim, persistState: { path: ${JSON.stringify(path.join(portal, ".wrangler", "state"))} } })],
    server: { port: 5173, strictPort: true },
    resolve: { alias: { "@": new URL("${rel}/src", import.meta.url).pathname } },
  }),
  {},
);
`,
  );
  return cfg;
}
